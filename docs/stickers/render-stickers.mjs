/**
 * Renders the Jubilee die-cut stickers to print-ready transparent PNGs.
 *
 *   node docs/stickers/render-stickers.mjs
 *
 * Playwright is borrowed from e2e/node_modules (run `npm install` in e2e/ first).
 *
 * Each sticker's .stage element is exactly 900 x 900 CSS px, which at
 * deviceScaleFactor 1 is 900 x 900 device px = 3 inches at 300 DPI.
 * omitBackground is what makes the outside of the die cut transparent.
 */
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..', '..');
const moduleRoot = process.env.JUBILEE_MODULE_ROOT ?? path.join(repoRoot, 'e2e');

const require = createRequire(pathToFileURL(path.join(moduleRoot, 'package.json')));
const { chromium } = require('@playwright/test');

const STICKERS = [
  { slug: 'sticker-1-logo', title: 'Logo' },
  { slug: 'sticker-2-app-icon', title: 'App icon' },
  { slug: 'sticker-3-night-badge', title: 'Night badge' },
  { slug: 'sticker-4-not-sundays', title: 'Not Sundays' },
  { slug: 'sticker-5-christian-owned', title: 'Christian-owned' },
];

/** The faces every sticker must have loaded; a fallback face fails the run. */
const FACES = [
  ['Archivo', '800 28px "Archivo"'],
  ['Inter', '600 30px "Inter"'],
];

/** PNG header reader: enough to assert dimensions and pixel format. */
function readPngHeader(buffer) {
  return {
    width: buffer.readUInt32BE(16),
    height: buffer.readUInt32BE(20),
    colourType: buffer.readUInt8(25), // 6 = truecolour with alpha
  };
}

const browser = await chromium.launch({
  args: ['--allow-file-access-from-files', '--font-render-hinting=none'],
});

/**
 * Lifts the <svg> out of a sticker's HTML into a standalone, editable file.
 * Generated so the SVG can never drift from the PNG. A standalone SVG cannot
 * link the stylesheet, so the faces (as data URIs, which also load when the SVG
 * is embedded as an image) and the artwork rules are inlined from stickers.css.
 */
async function exportSvg(slug, title) {
  const html = await readFile(path.join(here, 'src', `${slug}.html`), 'utf8');
  const css = await readFile(path.join(here, 'src', 'stickers.css'), 'utf8');

  const fontFaces = (
    await Promise.all(
      [...css.matchAll(/@font-face\s*\{[^}]*\}/g)].map(async (m) => {
        const ref = m[0].match(/url\("([^"]+)"\)/);
        const data = (await readFile(path.join(here, 'src', ref[1]))).toString('base64');
        return m[0]
          .replace(/\/\*[\s\S]*?\*\//g, '')
          .replace(/url\("[^"]+"\)/, `url("data:font/woff2;base64,${data}")`);
      }),
    )
  ).join('\n');
  const idioms = css.slice(css.indexOf('/* --- Shared artwork idioms')).trim();

  const svgOpen = html.search(/<svg[\s>]/);
  const svgTagEnd = html.indexOf('>', svgOpen);
  const inner = html.slice(svgTagEnd + 1, html.lastIndexOf('</svg>'));

  const svg = `<?xml version="1.0" encoding="UTF-8"?>
<!--
  Jubilee die-cut sticker: ${title}
  Generated by docs/stickers/render-stickers.mjs from src/${slug}.html.
  Edit the HTML, not this file.

  The die cut is the outer edge of the white rim (the #cut group), which is
  also the alpha edge of ${slug}.png. Text is live: outline it before sending
  this SVG to a printer that is not rasterising the PNG.
-->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 900 900" width="3in" height="3in">
  <defs>
    <style>
${fontFaces.replace(/^/gm, '      ')}

${idioms.replace(/^/gm, '      ')}
    </style>
  </defs>
${inner.trimEnd()}
</svg>
`;
  await writeFile(path.join(here, `${slug}.svg`), svg);
}

async function render(slug, { preview }) {
  const context = await browser.newContext({
    viewport: { width: 1100, height: 1100 },
    deviceScaleFactor: 1,
    reducedMotion: 'reduce',
  });
  const page = await context.newPage();
  await page.goto(pathToFileURL(path.join(here, 'src', `${slug}.html`)).href, { waitUntil: 'load' });

  if (preview) await page.evaluate(() => document.body.classList.add('preview'));

  const missing = await page.evaluate(async (faces) => {
    await Promise.all(faces.map(([, spec]) => document.fonts.load(spec).catch(() => {})));
    await document.fonts.ready;
    return faces.filter(([, spec]) => !document.fonts.check(spec)).map(([name]) => name);
  }, FACES);
  if (missing.length) {
    throw new Error(`${slug}: web fonts did not load: ${missing.join(', ')}`);
  }

  const out = path.join(here, preview ? `${slug}-preview.png` : `${slug}.png`);
  await page.locator('.stage').screenshot({ path: out, omitBackground: !preview, animations: 'disabled' });
  await context.close();
  return out;
}

/** Decodes the exported PNG and reports the alpha bounding box, which is the die cut. */
async function measureAlpha(pngPath) {
  const context = await browser.newContext();
  const page = await context.newPage();
  const dataUri = `data:image/png;base64,${(await readFile(pngPath)).toString('base64')}`;
  const result = await page.evaluate(async (uri) => {
    const img = new Image();
    img.src = uri;
    await img.decode();
    const canvas = document.createElement('canvas');
    canvas.width = img.width;
    canvas.height = img.height;
    const ctx = canvas.getContext('2d', { willReadFrequently: true });
    ctx.drawImage(img, 0, 0);
    const { data } = ctx.getImageData(0, 0, img.width, img.height);
    let minX = img.width;
    let minY = img.height;
    let maxX = -1;
    let maxY = -1;
    for (let y = 0; y < img.height; y += 1) {
      for (let x = 0; x < img.width; x += 1) {
        if (data[(y * img.width + x) * 4 + 3] > 8) {
          if (x < minX) minX = x;
          if (x > maxX) maxX = x;
          if (y < minY) minY = y;
          if (y > maxY) maxY = y;
        }
      }
    }
    const at = (x, y) => data[(y * img.width + x) * 4 + 3];
    return {
      minX,
      minY,
      maxX,
      maxY,
      corners: [at(0, 0), at(img.width - 1, 0), at(0, img.height - 1), at(img.width - 1, img.height - 1)],
    };
  }, dataUri);
  await context.close();
  return result;
}

try {
  for (const { slug, title } of STICKERS) {
    const printPath = await render(slug, { preview: false });
    await render(slug, { preview: true });

    const { width, height, colourType } = readPngHeader(await readFile(printPath));
    if (width !== 900 || height !== 900) {
      throw new Error(`${slug}: expected 900x900, got ${width}x${height}`);
    }
    if (colourType !== 6) {
      throw new Error(`${slug}: expected RGBA (colour type 6), got ${colourType}`);
    }

    const { minX, minY, maxX, maxY, corners } = await measureAlpha(printPath);
    if (corners.some((a) => a !== 0)) {
      throw new Error(`${slug}: corners are not transparent (${corners.join(',')})`);
    }
    if (minX < 2 || minY < 2 || maxX > width - 3 || maxY > height - 3) {
      throw new Error(
        `${slug}: artwork touches the canvas edge (x ${minX}-${maxX}, y ${minY}-${maxY}); the die cut would be clipped`,
      );
    }

    await exportSvg(slug, title);

    const artW = maxX - minX + 1;
    const artH = maxY - minY + 1;
    const inches = (px) => (px / 300).toFixed(2);
    console.log(
      `✓ ${title.padEnd(16)} ${path.basename(printPath).padEnd(30)} cut ${artW}x${artH}px (${inches(artW)}" x ${inches(artH)}")  margins L${minX} R${width - 1 - maxX} T${minY} B${height - 1 - maxY}`,
    );
  }

  // Contact sheet: the whole set at review size, three to a row. The tiles are
  // data URIs because a setContent page cannot load file:// images.
  const context = await browser.newContext({ viewport: { width: 1500, height: 620 } });
  const page = await context.newPage();
  const tiles = (
    await Promise.all(
      STICKERS.map(async ({ slug, title }) => {
        const data = (await readFile(path.join(here, `${slug}.png`))).toString('base64');
        return `<figure><img src="data:image/png;base64,${data}" width="380"><figcaption>${title}</figcaption></figure>`;
      }),
    )
  ).join('');
  await page.setContent(
    `<body style="margin:0;padding:40px;width:1212px;background:#f4f2ec;display:flex;flex-wrap:wrap;gap:36px;align-items:flex-start;font:600 16px system-ui;color:#0b0e14">
       <style>figure{margin:0;text-align:center}figcaption{margin-top:14px}img{display:block;filter:drop-shadow(0 10px 18px rgba(11,14,20,.18))}</style>
       ${tiles}
     </body>`,
  );
  await page.waitForTimeout(500);
  await page.locator('body').screenshot({ path: path.join(here, 'contact-sheet.png') });
  await context.close();
  console.log(`✓ ${'contact sheet'.padEnd(16)} contact-sheet.png`);
} finally {
  await browser.close();
}
