#!/usr/bin/env python3
"""Synthesize a video's narration from its script.md with Kokoro-82M (Hugging Face, run locally, free).

    python tools/video-audio/generate_audio.py docs/videos/NN-topic [--dry-run] [--voice af_heart] [--speed 1.1]

Writes, next to script.md:
    narration.wav   the narration alone, starting at 0 s
    timing.js       window.TIMING = sections and sentences with start/end seconds (the deck is cued from it)

The model and voice are downloaded once from huggingface.co/onnx-community/Kokoro-82M-v1.0-ONNX into
.cache/kokoro (KOKORO_DIR overrides). Needs: pip install kokoro-onnx soundfile numpy.
"""
import argparse, json, os, re, sys, urllib.request
from pathlib import Path

REPO = "https://huggingface.co/onnx-community/Kokoro-82M-v1.0-ONNX/resolve/main"
SENTENCE_GAP, SECTION_GAP = 0.10, 0.22
WPM = 175  # dry-run estimate at speed 1.0


def parse(path: Path):
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or not lines[0].startswith("# "):
        sys.exit("script.md: first line must be '# NN · Title'")
    sections, cur = [], None
    for n, line in enumerate(lines[1:], 2):
        s = line.strip()
        if not s:
            continue
        if s.startswith("## "):
            cur = {"title": s[3:].strip(), "sentences": []}
            sections.append(cur)
        elif re.match(r"^(\||```|<|#)", s) or "](" in s:
            sys.exit(f"script.md:{n}: tables, code fences, links, HTML and deeper headings are not allowed")
        else:
            if cur is None:
                cur = {"title": "", "sentences": []}
                sections.append(cur)
            cur["sentences"] += [x for x in re.split(r"(?<=[.!?])\s+", s.lstrip("- ")) if x]
    return lines[0][2:].strip(), sections


def fetch(url: str, dest: Path):
    if dest.exists() and dest.stat().st_size > 0:
        return
    dest.parent.mkdir(parents=True, exist_ok=True)
    print(f"downloading {url}")
    tmp = dest.with_suffix(dest.suffix + ".part")
    urllib.request.urlretrieve(url, tmp)
    tmp.rename(dest)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("folder", type=Path)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--voice", default=os.environ.get("KOKORO_VOICE", "af_heart"))
    ap.add_argument("--speed", type=float, default=1.1)
    a = ap.parse_args()

    title, sections = parse(a.folder / "script.md")
    words = sum(len(s.split()) for sec in sections for s in sec["sentences"])
    print(f"{title}: {len(sections)} sections, {words} words, about {words / WPM / a.speed * 60:.0f} s of speech")
    if a.dry_run:
        return

    import numpy as np, soundfile as sf
    from kokoro_onnx import Kokoro

    cache = Path(os.environ.get("KOKORO_DIR", ".cache/kokoro"))
    fetch(f"{REPO}/onnx/model.onnx", cache / "kokoro.onnx")
    fetch(f"{REPO}/voices/{a.voice}.bin", cache / f"{a.voice}.bin")
    # kokoro-onnx reads voices from an .npz; the Hub ships one raw float32 file per voice.
    npz = cache / f"{a.voice}.npz"
    style = np.fromfile(cache / f"{a.voice}.bin", dtype=np.float32).reshape(-1, 1, 256)
    np.savez(npz, **{a.voice: style})
    tts = Kokoro(str(cache / "kokoro.onnx"), str(npz))

    lexicon = {}
    for p in (a.folder / "pronunciations.json", a.folder.parent / "pronunciations.json"):
        if p.exists():
            lexicon.update(json.loads(p.read_text(encoding="utf-8")))

    audio, t, sr, out = [], 0.0, 24000, []
    for sec in sections:
        entry = {"title": sec["title"], "start": round(t, 3), "sentences": []}
        for text in sec["sentences"]:
            spoken = text
            for k, v in lexicon.items():
                spoken = spoken.replace(k, v)
            samples, sr = tts.create(spoken, voice=a.voice, speed=a.speed, lang="en-us")
            samples = np.asarray(samples, dtype=np.float32)
            dur = len(samples) / sr
            entry["sentences"].append({"text": text, "start": round(t, 3), "end": round(t + dur, 3)})
            audio += [samples, np.zeros(int(SENTENCE_GAP * sr), dtype=np.float32)]
            t += dur + SENTENCE_GAP
        audio.append(np.zeros(int((SECTION_GAP - SENTENCE_GAP) * sr), dtype=np.float32))
        entry["end"] = round(t - SENTENCE_GAP, 3)
        t += SECTION_GAP - SENTENCE_GAP
        out.append(entry)

    wav = np.concatenate(audio)
    wav = wav / max(1e-6, float(np.abs(wav).max())) * 0.89
    sf.write(a.folder / "narration.wav", wav, sr, subtype="PCM_16")
    total = round(out[-1]["end"], 3)
    (a.folder / "timing.js").write_text(
        "// Generated by tools/video-audio/generate_audio.py. Do not edit.\n"
        f"window.TIMING = {json.dumps({'voice': a.voice, 'duration': total, 'sections': out}, indent=1)};\n",
        encoding="utf-8")
    print(f"narration {total:.1f} s, voice {a.voice}")


if __name__ == "__main__":
    main()
